final Map<String, RegExp> _parameterRoutes = <String, RegExp>{
  for (final String template in _templates.where((route) => route.contains('{id}')))
    template: RegExp('^${template.split('{id}').map(RegExp.escape).join('[^/]+')}\$'),
};

String connectionFailureRouteTemplate(String path) {
  final String? route = Uri.tryParse(path)?.path;
  if (route == null) return '/unknown';
  if (_templates.contains(route)) return route;
  for (final MapEntry<String, RegExp> entry in _parameterRoutes.entries) {
    if (entry.value.hasMatch(route)) return entry.key;
  }
  return '/unknown';
}
